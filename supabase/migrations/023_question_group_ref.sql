--
-- 原来把大题的共同题干抽出来单独存（group_stem），展示时只显示一次。实际用起来
-- 太繁琐：每道小问的编辑页都要维护那段文字，改一道还要写到同组每一道。
-- 改成把材料直接留在每道小问的题干里（重复没关系），只额外记一个"这是第几题"，
-- 用来把小问归成一组、编号成 1a/1b、以及错题重测时整题重做。
--
-- 用题号而不是比对题干文本，是因为题号就在卷面上（第 1 题、第 2 题…），
-- 让模型照着抄比让它判断"这两段材料是不是同一段"可靠得多。
--
-- 可重复执行。Apply in the Supabase SQL editor.

